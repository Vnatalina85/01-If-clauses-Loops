# Запрашиваем число у пользователя
n = int(input("Введите количество собранных грибов: "))

# Проверяем, отрицательное ли число
if n < 0:
    print("Input error")
else:
    # Определяем правильную форму слова "гриб"
    # Если число заканчивается на 1, но не равно 11
    if n % 10 == 1 and n % 100 != 11:
        word = "гриб"
    # Если число заканчивается на 2, 3 или 4, но не равно 12, 13, 14
    elif n % 10 in [2, 3, 4] and n % 100 not in [12, 13, 14]:
        word = "гриба"
    # Во всех остальных случаях
    else:
        word = "грибов"
    
    # Выводим результат
    print(f"Мы собрали {n} {word}")